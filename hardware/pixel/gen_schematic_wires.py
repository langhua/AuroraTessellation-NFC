        #   ⇒ 不许 ✓：非轴对齐只走 L 形 / 45° dogleg / 走通道 ✓
    out.append([a, (b[0], a[1]), b])           # L 形
    out.append([a, (a[0], b[1]), b])
    dx, dy = b[0] - a[0], b[1] - a[1]
    sx = 1.0 if dx >= 0 else -1.0

def free_runs(iv, lo, hi, min_gap):
    r"""占位区间 `iv`（可重叠 ✓，内部会排序 ✓）在 `[lo, hi]` 里的**空档** ✓

    ★ 只返回**宽度 ≥ `min_gap`** 的空档 ✓（窄得放不下线的直接不算 ✓）。
    """
    out, cur = [], lo
    for a, b in sorted(iv):
        if a - cur >= min_gap:
            out.append((cur, a))
        cur = max(cur, b)
    if hi - cur >= min_gap:
        out.append((cur, hi))
    return out



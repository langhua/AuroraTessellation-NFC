/*
 * probe3.c —— 「示波器/逻辑分析仪探针」：在 PC6 上**连续不停地**发 WS2812 位流
 *
 * 为什么要有它 ✓（2026-11-07）
 *   正常固件 0.5 秒才发 32 µs 的一帧（占 0.006%），逻辑分析仪很难碰上 ✗
 *   这一版**连间隔都不留**，一上电就一直在发 ⇒ 任何时间按“采集”都抓得到波形 ✓
 *
 * 发的数据 = 0xA5 = 1010 0101 ⇒ '1' 和 '0' 交替出现，
 * 一次采集就能同时量到两种位宽 ✓
 *
 * 期望值（24 MHz，见 ws2812_gpio.c）：
 *   '1' 高 ≈ 0.875 µs ｜ '0' 高 ≈ 0.333 µs ｜ 位周期 ≈ 1.1–1.33 µs
 */
#include "regs.h"
#include "ws2812.h"

int main(void)
{
    ws_init();
    for (;;) {
        ws_send_byte(0xA5u);
        ws_send_byte(0xA5u);
        ws_send_byte(0xA5u);
    }
}
